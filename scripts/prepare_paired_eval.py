#!/usr/bin/env python3
"""Freeze a 500-row, labeled BFCL workload for the paired latency experiment.

This is a stratified diagnostic workload, not BFCL's official aggregate.  The
only new source fetched here is the pinned BFCL v4 irrelevance file.  Its
category label supplies the no-tool target; no labels are generated by Reflex.
"""

import hashlib
import json
import random
import urllib.request
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REV = "6ea57973c7a6097fd7c5915698c54c17c5b1b6c8"
BASE = (f"https://raw.githubusercontent.com/ShishirPatil/gorilla/{REV}/"
        "berkeley-function-call-leaderboard/bfcl_eval/data/")
OUT = ROOT / "data/bfcl/paired_eval_500.jsonl"


def normalized(text):
    return " ".join(text.strip().casefold().split())


def select(rows, count, seed):
    ordered = sorted(rows, key=lambda r: r["id"])
    return random.Random(seed).sample(ordered, count)


def fetch_category(category):
    url = BASE + f"BFCL_v4_{category}.json"
    req = urllib.request.Request(url, headers={"User-Agent": "Reflex-Research-Benchmark"})
    with urllib.request.urlopen(req, timeout=60) as response:
        raw = response.read()
    return url, raw, [json.loads(line) for line in raw.splitlines() if line.strip()]


def main():
    live_path = ROOT / "data/bfcl/live_eval.jsonl"
    live_bytes = live_path.read_bytes()
    live = [json.loads(line) for line in live_bytes.splitlines() if line.strip()]
    buckets = {bucket: [r for r in live if r["arg_bucket"] == bucket]
               for bucket in ("atomic", "primitive", "freetext")}
    assert {k: len(v) for k, v in buckets.items()} == {
        "atomic": 25, "primitive": 974, "freetext": 52,
    }, "Pinned live evaluation set changed; inspect before regenerating"
    selected = (select(buckets["atomic"], 25, 23)
                + select(buckets["primitive"], 303, 23)
                + select(buckets["freetext"], 52, 23))

    irrelevant_url, irrelevant_raw, irrelevant = fetch_category("irrelevance")
    live_irrelevant_url, live_irrelevant_raw, live_irrelevant = fetch_category("live_irrelevance")
    assert len(irrelevant) == 240
    old_queries = set()
    for split in ("train", "cal", "test"):
        for line in (ROOT / f"data/bfcl/{split}.jsonl").read_text().splitlines():
            old_queries.add(normalized(json.loads(line)["user_query"]))
    old_queries.update(normalized(r["user_query"]) for r in selected)
    def convert_no_tool(items, source):
        converted = []
        for r in items:
            turns = r.get("question", [])
            if not turns or not turns[0]:
                continue
            query = turns[0][0].get("content", "")
            if not query or normalized(query) in old_queries:
                continue
            functions = r.get("function", [])
            if not functions:
                continue
            converted.append({
                "id": r["id"], "user_query": query,
                "candidate_functions": functions,
                "ground_truth_label": None, "gold_args": None,
                "arg_bucket": "no_tool", "source": source,
                "num_candidates": len(functions),
            })
        return converted

    no_tool_nonlive = convert_no_tool(irrelevant, "BFCL_v4_irrelevance")
    no_tool_live = convert_no_tool(live_irrelevant, "BFCL_v4_live_irrelevance")
    atomic_distractors = [r for r in no_tool_live if any(
        not (f.get("parameters") or {}).get("properties") for f in r["candidate_functions"]
    )]
    assert len(atomic_distractors) == 43, "Inspect pinned source if count changes"
    assert len(no_tool_nonlive) >= 77
    selected += atomic_distractors + select(no_tool_nonlive, 77, 23)
    assert len(selected) == 500 and len({r["id"] for r in selected}) == 500
    random.Random(2309).shuffle(selected)
    OUT.write_text("".join(json.dumps(row, ensure_ascii=False) + "\n" for row in selected))
    metadata = {
        "source_revision": REV,
        "live_eval_source": "data/bfcl/live_eval.jsonl",
        "live_eval_sha256": hashlib.sha256(live_bytes).hexdigest(),
        "irrelevance_source_url": irrelevant_url,
        "irrelevance_raw_sha256": hashlib.sha256(irrelevant_raw).hexdigest(),
        "live_irrelevance_source_url": live_irrelevant_url,
        "live_irrelevance_raw_sha256": hashlib.sha256(live_irrelevant_raw).hexdigest(),
        "selection": "all 25 atomic, 52 freetext, and 43 live no-tool with atomic distractors; seeded sample of 303 primitive and 77 nonlive no-tool; seed 23; shuffled seed 2309",
        "no_tool_label": "BFCL_v4_irrelevance and BFCL_v4_live_irrelevance categories (no applicable offered tool)",
        "counts": dict(Counter(r["arg_bucket"] for r in selected)),
        "sha256": hashlib.sha256(OUT.read_bytes()).hexdigest(),
        "limitations": "Diagnostic stratified workload; no official BFCL aggregate; only 24 of 25 empty-gold calls have truly empty schemas.",
    }
    OUT.with_suffix(".provenance.json").write_text(json.dumps(metadata, indent=2) + "\n")
    print(json.dumps(metadata, indent=2))


if __name__ == "__main__":
    main()
