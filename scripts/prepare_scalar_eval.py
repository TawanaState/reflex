#!/usr/bin/env python3
"""Freeze BFCL rows that can test typed-scalar draft exits and false exits."""

import hashlib
import json
import random
import urllib.request
from collections import Counter
from pathlib import Path

from src.schema.inspector import Tier, inspect_tool_schema

ROOT = Path(__file__).resolve().parents[1]
REV = "6ea57973c7a6097fd7c5915698c54c17c5b1b6c8"
URL = (f"https://raw.githubusercontent.com/ShishirPatil/gorilla/{REV}/"
       "berkeley-function-call-leaderboard/bfcl_eval/data/BFCL_v4_live_irrelevance.json")
OUT = ROOT / "data/bfcl/scalar_eval.jsonl"


def norm(text):
    return " ".join(text.strip().casefold().split())


def choose(rows, n, seed):
    return random.Random(seed).sample(sorted(rows, key=lambda r: r["id"]), n)


def is_scalar(schema):
    profile = inspect_tool_schema(schema)
    return profile.tier == Tier.PARAMETRIC_PRIMITIVE and bool(profile.parameters)


def main():
    live_path = ROOT / "data/bfcl/live_eval.jsonl"
    live_bytes = live_path.read_bytes()
    live = [json.loads(line) for line in live_bytes.splitlines() if line.strip()]
    scalar_positive = []
    for row in live:
        gold_schema = next((f for f in row["candidate_functions"]
                            if f["name"] == row["ground_truth_label"]), None)
        if gold_schema is not None and is_scalar(gold_schema) and row["arg_bucket"] != "atomic":
            scalar_positive.append({**row, "eval_bucket": "scalar_positive"})
    assert len(scalar_positive) == 58, "Inspect pinned live set if eligible count changes"
    atomic = [{**r, "eval_bucket": "atomic_control"} for r in live if r["arg_bucket"] == "atomic"]
    assert len(atomic) == 25
    open_text = [{**r, "eval_bucket": "open_text_control"} for r in
                 choose([r for r in live if r["arg_bucket"] == "freetext"
                         and r["id"] not in {s["id"] for s in scalar_positive}], 31, 2309)]
    selected = scalar_positive + atomic + open_text

    request = urllib.request.Request(URL, headers={"User-Agent": "Reflex-Scalar-Research"})
    with urllib.request.urlopen(request, timeout=60) as response:
        raw = response.read()
    irrelevance = [json.loads(line) for line in raw.splitlines() if line.strip()]
    assert len(irrelevance) == 884
    old_queries = set()
    for split in ("train", "cal", "test"):
        for line in (ROOT / f"data/bfcl/{split}.jsonl").read_text().splitlines():
            old_queries.add(norm(json.loads(line)["user_query"]))
    old_queries.update(norm(r["user_query"]) for r in selected)
    scalar_negatives = []
    for item in irrelevance:
        if not item.get("question") or not item["question"][0]:
            continue
        query = item["question"][0][0].get("content", "")
        functions = item.get("function", [])
        if not query or norm(query) in old_queries or not functions:
            continue
        if not any(is_scalar(f) for f in functions):
            continue
        scalar_negatives.append({
            "id": item["id"], "user_query": query,
            "candidate_functions": functions,
            "ground_truth_label": None, "gold_args": None,
            "arg_bucket": "no_tool", "eval_bucket": "no_tool_scalar_distractor",
            "source": "BFCL_v4_live_irrelevance", "num_candidates": len(functions),
        })
    both = [r for r in scalar_negatives if any(
        inspect_tool_schema(f).tier == Tier.ATOMIC for f in r["candidate_functions"]
    )]
    scalar_only = [r for r in scalar_negatives if r not in both]
    assert len(both) >= 20 and len(scalar_only) >= 71
    selected += both + choose(scalar_only, 100 - len(both), 2309)
    assert len(selected) == 214 and len({r["id"] for r in selected}) == 214
    random.Random(20260924).shuffle(selected)
    OUT.write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in selected))
    provenance = {
        "source_revision": REV,
        "live_eval_sha256": hashlib.sha256(live_bytes).hexdigest(),
        "live_irrelevance_url": URL,
        "live_irrelevance_sha256": hashlib.sha256(raw).hexdigest(),
        "selection": "all 58 nonempty eligible scalar gold calls, all 25 atomic controls, 31 seeded open-text controls, and 100 no-tool scalar-distractor cases (all atomic+scalar menus then seeded remainder)",
        "seed": 2309,
        "counts": dict(Counter(r["eval_bucket"] for r in selected)),
        "sha256": hashlib.sha256(OUT.read_bytes()).hexdigest(),
        "note": "Diagnostic selected workload, not official BFCL aggregate. No labels or latency values generated by Reflex.",
    }
    OUT.with_suffix(".provenance.json").write_text(json.dumps(provenance, indent=2) + "\n")
    print(json.dumps(provenance, indent=2))


if __name__ == "__main__":
    main()
